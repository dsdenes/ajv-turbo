"use strict";

const test = require("node:test");
const assert = require("node:assert");
const path = require("node:path");

const {ROOT, hashDirectory, runWithBothValidators} = require("./lib/project");

const SOURCE_PROJECT = path.join(__dirname, "fixtures", "code-process-project");
const WORK_PROJECT = path.join(ROOT, ".tmp", "code-process-project");
const NAMESPACE = "https://example.test/code-process/";

const MISSING_VALUE = {
  instancePath: "",
  schemaPath: "#/required",
  keyword: "required",
  params: {missingProperty: "value"},
  message: "must have required property 'value'",
};

test("a project's code rewrite produces every validator it compiles", () => {
  const before = hashDirectory(SOURCE_PROJECT);
  const {reference, replacement} = runWithBothValidators(SOURCE_PROJECT, WORK_PROJECT, {}, [
    "generated",
  ]);

  assert.strictEqual(hashDirectory(SOURCE_PROJECT), before, "fixture project was edited");
  assert.deepStrictEqual(replacement, reference);
  assert.strictEqual(reference.length, 4, "expected every dialect entry point");

  const byDialect = new Map(reference.map((result) => [result.case, result.results]));
  assert.deepStrictEqual([...byDialect.keys()], ["draft7", "2019", "2020", "jtd"]);

  for (const [dialect, results] of byDialect) {
    const label = `${dialect}: `;

    // The rewrite sees each compilation once, in compile order, and is not
    // called again when the same schema is compiled twice.
    assert.deepStrictEqual(
      results.count.calls,
      [NAMESPACE + dialect + "-count", NAMESPACE + dialect + "-count-next"],
      label + "rewrite did not run once per compiled validator, in compile order",
    );
    assert.strictEqual(results.count.sameValidator, true, label + "second compile reused nothing");
    assert.strictEqual(results.count.valid.valid, true);
    assert.strictEqual(results.count.valid.errors, null);
    assert.strictEqual(results.count.invalid.valid, false);
    assert.deepStrictEqual(results.count.invalid.errors, [
      dialect === "jtd"
        ? {
            instancePath: "",
            schemaPath: "/properties/value",
            keyword: "properties",
            params: {error: "missing", missingProperty: "value"},
            message: "must have property 'value'",
          }
        : MISSING_VALUE,
    ]);
    assert.strictEqual(
      results.count.text,
      dialect === "jtd"
        ? "data must have property 'value'"
        : "data must have required property 'value'",
    );
    assert.strictEqual(results.count.again.valid, true);
    assert.strictEqual(results.count.next.valid, true);

    // The rewritten validator is what validates documents, in both directions.
    assert.deepStrictEqual(results.reject, {valid: false, errors: null});
    assert.deepStrictEqual(results.accept, {valid: true, errors: null});
    assert.deepStrictEqual(results.patched, {valid: false, errors: null});

    // A rewrite that throws fails compilation with its own error and produces
    // no validator.
    assert.deepStrictEqual(results.throwing, {produced: null, failure: "rewrite exploded"});

    // Without a rewrite the validator stays exactly as it was.
    assert.strictEqual(results.plain.valid.valid, true);
    assert.strictEqual(results.plain.invalid.valid, false);
    assert.deepStrictEqual(results.plain.invalid.errors, results.count.invalid.errors);

    // Asynchronous validators go through the rewrite as well.
    assert.deepStrictEqual(results.asyncCount.calls, [NAMESPACE + dialect + "-async"]);
    assert.strictEqual(results.asyncCount.$async, true);
    assert.strictEqual(results.asyncRewrite.settled, "rejected");
    assert.strictEqual(results.asyncRewrite.message, "rewritten async failure");

    // Standalone modules generated by an instance that supplies a rewrite keep
    // the unrewritten validator's verdicts and reports.
    assert.deepStrictEqual(results.standalone.rewritten, results.standalone.plain);
    assert.strictEqual(results.standalone.rewritten.valid.valid, true);
    assert.strictEqual(results.standalone.rewritten.invalid.valid, false);
    assert.deepStrictEqual(
      results.standalone.rewritten.invalid.errors,
      results.count.invalid.errors,
    );
  }
});
